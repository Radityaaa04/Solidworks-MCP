        result = manager.get_mass_properties()
        self.assertEqual(result["material"], "domains_steel")
        self.assertEqual(result["mass_kg"], 0.012)
        self.assertEqual(result["moments_of_inertia_cg_kg_m2"]["Lzz"], 8)
