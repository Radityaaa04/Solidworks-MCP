class Property:
    def __init__(self, getter, setter=None):
        self.getter = getter
        self.setter = setter


class StrictCOM:
    """No autogenerated attributes, implicit methods, or real dispatch objects."""
    __slots__ = ("_values", "reads", "writes", "label")

    def __init__(self, label, **values):
        object.__setattr__(self, "label", label)
        object.__setattr__(self, "_values", values)
        object.__setattr__(self, "reads", [])
        object.__setattr__(self, "writes", [])

    def __getattr__(self, name):
        values = object.__getattribute__(self, "_values")
        if name not in values:
            raise AttributeError(f"{self.label}: undeclared COM member {name}")
        self.reads.append(name)
        value = values[name]
        return value.getter() if isinstance(value, Property) else value

    def __setattr__(self, name, value):
        values = object.__getattribute__(self, "_values")
        if name not in values:
            raise AttributeError(f"{self.label}: undeclared COM assignment {name}")
        self.writes.append((name, value))
        old = values[name]
        if isinstance(old, Property):
            if old.setter is None:
                raise AttributeError(f"{self.label}.{name} is read-only")
            old.setter(value)
        else:
            values[name] = value


def raising(exception):
    def fail():
        raise exception
    return fail


class OfflineBoundaryError(AssertionError):
    pass


def blocked(operation):
    def deny(*args, **kwargs):
        GUARD_EVENTS.append({"operation": operation, "args": repr(args)})
        raise OfflineBoundaryError(f"Offline boundary: {operation}")
    return deny


class GuardedModule(types.ModuleType):
    def __getattr__(self, name):
        if name.startswith("__"):
            raise AttributeError(name)
        return blocked(f"{self.__name__}.{name}")


class Variant:
    """In-memory OLE value carrier; intentionally not a pywin32 COM object."""
    __slots__ = ("varianttype", "value")

    def __init__(self, varianttype, value):
        self.varianttype = varianttype
        self.value = value


def install_com_stubs():
    # Only OLE VARTYPE constants are supplied. No SolidWorks enums are fabricated.
    pythoncom = GuardedModule("pythoncom")
    for name, value in {"VT_I4": 3, "VT_R8": 5, "VT_BSTR": 8,
                        "VT_DISPATCH": 9, "VT_BOOL": 11,
                        "VT_BYREF": 0x4000}.items():
        setattr(pythoncom, name, value)
    win32com = GuardedModule("win32com")
    win32com.__path__ = []
    client = GuardedModule("win32com.client")
    client.VARIANT = Variant
    win32com.client = client
    for name, module in (("pythoncom", pythoncom), ("win32com", win32com),
                         ("win32com.client", client)):
        if name in sys.modules:
            raise RuntimeError(f"Refusing to run after real {name} was imported")
        sys.modules[name] = module


def install_audit_guard():
    def check_write(path):
        if isinstance(path, int):
            return
        resolved = Path(os.fsdecode(path)).resolve()
        try:
            relative = resolved.relative_to(OUTPUT)
        except ValueError:
            blocked("filesystem write outside domains output")(str(resolved))
        else:
            if not relative.parts or not all(p.startswith("domains_") for p in relative.parts):
                blocked("filesystem write to non-domains artifact")(str(resolved))

    def audit(event, args):
        if (event.startswith("socket.") or event in {
            "subprocess.Popen", "os.system", "os.posix_spawn", "os.spawn",
            "os.startfile", "os.exec", "os.fork", "os.forkpty"
        }):
            blocked(event)(*args)
        if event == "open":
            path, mode, flags = args
            writing = (isinstance(mode, str) and any(c in mode for c in "wax+"))
            writing = writing or bool(flags & (os.O_WRONLY | os.O_RDWR | os.O_CREAT | os.O_TRUNC))
            if writing:
                check_write(path)
        elif event in {"os.mkdir", "os.remove", "os.rmdir"}:
            check_write(args[0])
        elif event in {"os.rename", "os.replace"}:
            check_write(args[0])
            check_write(args[1])
    sys.addaudithook(audit)


def plain(value):
    if isinstance(value, Variant):
        return {"vartype": value.varianttype, "value": plain(value.value)}
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, dict):
        return {str(k): plain(v) for k, v in value.items()}
    if isinstance(value, (tuple, list)):
        return [plain(v) for v in value]
    if isinstance(value, float) and not math.isfinite(value):
        return repr(value)
    if value is None or isinstance(value, (str, int, float, bool)):
        return value
    return repr(value)


class DomainCase(unittest.TestCase):
    def setUp(self):
        global FIXTURE_SEQUENCE
        FIXTURE_SEQUENCE += 1
        self.fixture_dir = FIXTURES / f"domains_{FIXTURE_SEQUENCE:03d}"
        list(FIXTURES.iterdir())  # Verify/list parent before creating fixtures.
        self.fixture_dir.mkdir()
        self.observations = []

    def path(self, name):
        if not name.startswith("domains_"):
            raise AssertionError("Every fixture must use the domains_ prefix")
        list(self.fixture_dir.iterdir())
        return self.fixture_dir / name

    def file(self, name, contents=b"domains fixture, not a real CAD document"):
        path = self.path(name)
        path.write_bytes(contents)
        return path

    def observe(self, finding, **evidence):
        self.observations.append({"level": "info", "finding": finding,
                                  "evidence": plain(evidence)})

    def doc_manager(self, doc, app=None):
        if app is None:
            app = StrictCOM("unused application")
        client = StrictCOM("fake client", app=app)
        return StrictCOM("fake DocumentManager", client=client,
                         get_active_doc=method(lambda: doc))


