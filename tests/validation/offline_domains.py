class RecordingResult(unittest.TextTestResult):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.records = []
        self.current = {}

    def startTest(self, test):
        super().startTest(test)
        self.current[test.id()] = {"test_id": test.id(), "domain": test.__class__.__name__,
            "contract": test.shortDescription(), "started_utc": utc_now(),
            "status": None, "traceback": None, "skip_reason": None,
            "_clock": time.perf_counter()}

    def outcome(self, test, status, err=None, reason=None):
        record = self.current[test.id()]
        record["status"] = status
        if err is not None:
            record["traceback"] = "".join(traceback.format_exception(*err))
        record["skip_reason"] = reason

    def addSuccess(self, test):
        self.outcome(test, "pass")
        super().addSuccess(test)

    def addFailure(self, test, err):
        self.outcome(test, "fail", err)
        super().addFailure(test, err)

    def addError(self, test, err):
        self.outcome(test, "error", err)
        super().addError(test, err)

    def addSkip(self, test, reason):
        self.outcome(test, "skip", reason=reason)
        super().addSkip(test, reason)

    def stopTest(self, test):
        record = self.current.pop(test.id())
        record["elapsed_seconds"] = round(time.perf_counter() - record.pop("_clock"), 6)
        record["observations"] = getattr(test, "observations", [])
        record["fixture_directory"] = str(getattr(test, "fixture_dir", ""))
        self.records.append(record)
        self.stream.writeln("DOMAINS_RESULT " + json.dumps(record, ensure_ascii=False, allow_nan=False))
        super().stopTest(test)


class Tee:
    def __init__(self, *streams):
        self.streams = streams

    def write(self, text):
        for stream in self.streams:
            stream.write(text)
        return len(text)

    def flush(self):
        for stream in self.streams:
            stream.flush()


def production_hashes(root):
    return {p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted((root / "src").rglob("*.py"))}


def write_json(path, data):
    list(path.parent.iterdir())
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False, allow_nan=False) + "\n", encoding="utf-8")


