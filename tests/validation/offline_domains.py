    def modern_mass(self, **changes):
        values = dict(Mass=0.012, Volume=0.000002, SurfaceArea=0.003,
                      CenterOfMass=(0.001, -0.002, 0.003), Density=6000.0,
                      GetMomentOfInertia=method(lambda where: tuple(range(9))))
